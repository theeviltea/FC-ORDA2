// Builds src/theme/tokens.ts from design/tokens.json (the ORDA Design System export).
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const map = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [camel(k), v]));

const shadow = Object.fromEntries(
  Object.entries(src.shadow).map(([k, v]) => {
    const blur = Number((v.match(/^\S+\s+\S+\s+(\d+)px/) || [])[1] ?? 8);
    return [camel(k), { boxShadow: v, elevation: Math.max(1, Math.round(blur / 4)) }];
  }),
);

const out = `// GENERATED by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand.
// Source of truth: ORDA Design System. Update design/tokens.json and run \`npm run tokens\`.

export const colors = ${JSON.stringify(map(src.color), null, 2)} as const;

export const gradients = ${JSON.stringify(map(src.gradient), null, 2)} as const;

export const radius = ${JSON.stringify(map(src.radius), null, 2)} as const;

export const spacing = ${JSON.stringify(map(src.spacing), null, 2)} as const;

export const shadows = ${JSON.stringify(shadow, null, 2)} as const;

export type ColorName = keyof typeof colors;
`;
writeFileSync(new URL('../src/theme/tokens.ts', import.meta.url), out);
console.log('tokens.ts written');
