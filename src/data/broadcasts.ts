/**
 * Рассылки из админки, которые не ведут ни в какой раздел приложения — просто сообщение клуба.
 * Пуш с такой рассылкой открывает экран `/message/[id]`.
 *
 * Текст приходит блоками. В абзацах поддерживаются `**жирный**` и ссылки `[текст](/путь или https://…)`.
 * Картинка и кнопка — необязательные.
 */
export type BroadcastBlock =
  | { type: 'lead'; text: string }
  | { type: 'p'; text: string }
  | { type: 'list'; title?: string; items: { icon: IconName; text: string }[] }
  | { type: 'quote'; text: string; by?: string };

export type Broadcast = {
  id: string;
  title: string;
  /** Метка над заголовком: «Новости клуба», «Информация»… */
  tag: string;
  /** Коротко для ленты уведомлений и шторки. */
  preview: string;
  /** Когда пришло: «Сегодня, 13:19». */
  when: string;
  /** Полная дата под текстом. */
  date: string;
  cover?: number;
  coverAlt?: string;
  blocks: BroadcastBlock[];
  button?: { label: string; icon?: IconName; href: string };
};

